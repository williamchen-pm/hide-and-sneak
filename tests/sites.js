// Real-site check: load popular public sites without the extension, then with Agent Mode and
// Presenting mode on, and compare. Reports new page errors, extra load time, layout changes,
// and anything hidden or locked (public pages have no secrets, so those are likely false
// positives worth reviewing). Writes docs/SITES.md.
// Usage: node tests/sites.js            (needs internet access to the sites below)
//        SITES=http://localhost:8766/demo/inbox.html node tests/sites.js   (dry run on local pages)
const fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const EXT = path.resolve(__dirname, '../extension');
const DEFAULT_SITES = [
  'https://en.wikipedia.org/wiki/Credit_card', 'https://www.bbc.com/news', 'https://www.theguardian.com/us', 'https://www.npr.org/',
  'https://www.nytimes.com/', 'https://www.cnn.com/', 'https://news.ycombinator.com/', 'https://stackoverflow.com/questions',
  'https://developer.mozilla.org/en-US/docs/Web/HTML/Element/input', 'https://github.com/williamchen-pm/hide-and-sneak',
  'https://docs.python.org/3/', 'https://www.amazon.com/', 'https://www.ebay.com/', 'https://www.target.com/', 'https://www.etsy.com/',
  'https://www.walmart.com/', 'https://www.zillow.com/', 'https://www.imdb.com/', 'https://www.weather.gov/', 'https://www.irs.gov/',
  'https://www.ssa.gov/', 'https://www.usa.gov/', 'https://www.healthcare.gov/', 'https://www.cdc.gov/', 'https://www.chase.com/',
  'https://www.bankofamerica.com/', 'https://www.paypal.com/us/home', 'https://www.indeed.com/', 'https://www.apple.com/', 'https://www.microsoft.com/en-us/',
];
const SITES = process.env.SITES ? process.env.SITES.split(',') : DEFAULT_SITES;
const PLACEHOLDER = /\[(?:[A-Z0-9 #]+)\]/g;

async function visit(ctx, url) {
  const p = await ctx.newPage(); const errors = [];
  p.on('pageerror', e => errors.push(e.message.slice(0, 120)));
  const t0 = Date.now();
  let ok = true;
  try { await p.goto(url, { waitUntil: 'load', timeout: 30000 }); } catch (e) { ok = false; }
  const loadMs = Date.now() - t0;
  await p.waitForTimeout(2500);
  const r = ok ? await p.evaluate((src) => {
    const re = new RegExp(src, 'g');
    const text = document.body ? document.body.innerText : '';
    const tokens = (text.match(re) || []).concat((document.title.match(re) || []));
    const locked = [...document.querySelectorAll('[data-hns-locked]')].map(e => ((e.getAttribute('aria-label') || '').match(/\(([^)]+)\)/) || [])[1] || e.name || e.id || e.type).slice(0, 8);
    const masked = document.querySelectorAll('[data-hns-masked]').length;
    return { tokens, locked, masked, height: document.documentElement.scrollHeight, injection: tokens.filter(t => t === '[AGENT INSTRUCTIONS REMOVED]').length };
  }, PLACEHOLDER.source).catch(() => null) : null;
  await p.close();
  return { ok: ok && !!r, loadMs, errors, ...(r || {}) };
}

(async () => {
  const base = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM || undefined });
  const baseCtx = await base.newContext();
  const ext = await chromium.launchPersistentContext('', { headless: true, executablePath: process.env.CHROMIUM || undefined,
    args: [`--disable-extensions-except=${EXT}`, `--load-extension=${EXT}`, '--headless=new'] });
  const sw = ext.serviceWorkers()[0] || await ext.waitForEvent('serviceworker');
  for (let i = 0; i < 40 && !(await sw.evaluate(() => typeof self.HNSSettings === 'object')); i++) await new Promise(r => setTimeout(r, 100));
  const version = await sw.evaluate(() => chrome.runtime.getManifest().version);
  const rows = [];
  for (const url of SITES) {
    const b = await visit(baseCtx, url);
    await sw.evaluate(async () => { await HNSSettings.setSettings({ mode: 'agent' }); await setAgentMode(true); });
    const a = await visit(ext, url);
    await sw.evaluate(async () => { await HNSSettings.setSettings({ mode: 'present' }); });
    const pr = await visit(ext, url);
    await sw.evaluate(() => setAgentMode(false));
    const newErrs = (x) => x.errors.filter(e => !b.errors.includes(e));
    rows.push({ url, b, a, pr, newErrA: newErrs(a), newErrP: newErrs(pr) });
    console.log(`${b.ok && a.ok ? 'OK ' : 'ERR'} ${url}  +${a.loadMs - b.loadMs}ms  tokens:${(a.tokens || []).length} locked:${(a.locked || []).length} newErrors:${newErrs(a).length}`);
  }
  await base.close(); await ext.close();
  const reached = rows.filter(r => r.b.ok && r.a.ok);
  const med = (xs) => { const s = xs.slice().sort((x, y) => x - y); return s.length ? s[Math.floor(s.length / 2)] : 0; };
  const date = new Date().toISOString().slice(0, 10);
  let md = `# Real-site check\n\n*${date} · Hide & Sneak ${version} · generated by \`node tests/sites.js\`*\n\n`;
  md += `Each site was loaded three times: without the extension, with Agent Mode on, and with Presenting mode on. Public pages hold no real secrets, so anything hidden or locked is listed for review as a possible false positive.\n\n`;
  md += `**Reached ${reached.length} of ${rows.length} sites.** New page errors caused by the extension: **${reached.filter(r => r.newErrA.length || r.newErrP.length).length}** sites. Median extra load time: **${med(reached.map(r => r.a.loadMs - r.b.loadMs))} ms**.\n\n`;
  md += `| Site | Extra load time | New errors | Layout change | Hidden (Agent Mode) | Locked fields |\n|---|---|---|---|---|---|\n`;
  for (const r of rows) {
    if (!(r.b.ok && r.a.ok)) { md += `| ${r.url} | not reached | | | | |\n`; continue; }
    const dh = r.b.height ? Math.round(Math.abs(r.a.height - r.b.height) / r.b.height * 100) : 0;
    const toks = [...new Set(r.a.tokens)].map(t => `\`${t}\`×${r.a.tokens.filter(x => x === t).length}`).join(' ') || '—';
    md += `| ${r.url} | ${r.a.loadMs - r.b.loadMs} ms | ${r.newErrA.length + r.newErrP.length || '—'} | ${dh > 5 ? dh + '%' : '—'} | ${toks} | ${r.a.locked.length ? r.a.locked.join(', ') : '—'} |\n`;
  }
  fs.writeFileSync(path.resolve(__dirname, '../docs/SITES.md'), md);
  console.log(`\nReached ${reached.length}/${rows.length}. Wrote docs/SITES.md`);
})();
